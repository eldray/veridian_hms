  // Search function with fuzzy matching
  export const searchComplaints = (searchTerm: string, limit: number = 20): string[] => {
    if (!searchTerm.trim()) return COMPLAINTS_CATALOG.slice(0, limit);
    
    const term = searchTerm.toLowerCase().trim();
    
    // Exact matches first
    const exactMatches = COMPLAINTS_CATALOG.filter(c => 
      c.toLowerCase() === term
    );
    
    // Contains matches
    const containsMatches = COMPLAINTS_CATALOG.filter(c => 
      c.toLowerCase().includes(term) && c.toLowerCase() !== term
    );
    
    // Word boundary matches (each word in search matches start of words in complaint)
    const words = term.split(/\s+/);
    const wordMatches = COMPLAINTS_CATALOG.filter(c => {
      const complaintLower = c.toLowerCase();
      return words.every(word => complaintLower.includes(word)) &&
             !containsMatches.includes(c) &&
             !exactMatches.includes(c);
    });
    
    return [...exactMatches, ...containsMatches, ...wordMatches].slice(0, limit);
  };