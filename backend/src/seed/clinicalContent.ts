// src/seed/clinicalContent.ts
// Narrative pools and encounter templates for the demo seed. These exist so a seeded record
// reads like a real encounter instead of the placeholder strings the seed used to repeat on
// every row ("Routine visit", "Patient reviewed. See diagnosis.").
//
// Everything here is free text or a plain tuple - no database access. Values that must be real
// foreign keys (ICD codes, investigation codes, scan codes, procedure codes, drug names) are
// written as the reference code and resolved against the database by the seed itself. A code
// the database does not have is dropped, never invented, so no link can be left dangling.
//
// Every code below was checked against src/data/diagnoses.json, labTests.json, scans.json,
// procedures.json and the medicine files. A scenario pointing at a code that does not exist
// silently produces an encounter with no diagnosis, so re-verify the codes when adding one.

// ═══════════════════════════════════════════════════════════
// ENCOUNTER SCENARIOS
//
// One scenario is a whole encounter: the story, the codes it gets investigated and diagnosed
// with, the drugs it is treated with, and how it disposes (home, admitted or daycase). The
// generator picks a scenario the patient can actually present with, so a man is never delivered
// a baby and a child is never booked for a cataract.
// ═══════════════════════════════════════════════════════════

export interface ComplaintScenario {
  /** Stable identifier; used for logging and for excluding a scenario from a seed run. */
  key: string;
  complaints: string;
  history: string;
  examination: string;
  assessment: string;
  treatmentPlan: string;
  /** ICD-10 codes (Diagnosis.code) this encounter can be closed with. */
  icdCodes: string[];
  /** LabTestTemplate.investigationCode a clinician would actually order here. */
  labCodes: string[];
  /** ScanTemplate.scanCode a clinician would actually order here. */
  scanCodes: string[];
  /** ProcedureTemplate.procedureCode performed for this presentation. */
  procedureCodes: string[];
  /** Keys of DRUG_GROUPS to prescribe from. */
  drugGroups: string[];
  /** ClinicalConditionOutcome. That enum has no "recovered" and no "transferred". */
  outcome: 'improved' | 'stable' | 'unchanged' | 'deteriorated' | 'deceased';
  /** AttendanceType values this scenario may be recorded under. */
  types: string[];
  minAge: number;
  maxAge: number;
  gender: 'male' | 'female' | 'any';
  /** Probability the encounter ends in an admission rather than a discharge home. */
  admitChance: number;
  admissionType: 'elective' | 'emergency' | 'transfer' | 'detention_observation';
  /** Length of stay range, in days, when admitted. */
  losDays: [number, number];
  /** Days until the follow-up appointment is booked. */
  followUpDays: number[];
  /** ConsultationType the provider belongs to; decides which doctor records the encounter. */
  specialization: 'General Medicine' | 'Surgery' | 'Obstetrics' | 'Pediatrics' | 'Internal Medicine';
  advice: string;
}

